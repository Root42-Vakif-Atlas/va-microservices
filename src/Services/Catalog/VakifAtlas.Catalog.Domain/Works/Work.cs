using VakifAtlas.Catalog.Domain.Complexes;
using VakifAtlas.Catalog.Domain.References;
using VakifAtlas.SharedKernel;

namespace VakifAtlas.Catalog.Domain.Works;

public class Work
{
    public long Id { get; set; }
    public string Key { get; set; } = null!; // also the Turkish URL slug
    public short CityCode { get; set; }
    public City City { get; set; } = null!;
    public string? District { get; set; }
    public long? ComplexId { get; set; }
    public int? ComplexPosition { get; set; } // set together with ComplexId
    public Complex? Complex { get; set; }
    public string? Address { get; set; }
    public string Category { get; set; } = WorkCategory.Other;
    public bool CategoryOverridden { get; set; } // false = Category follows the tr title (re-derived on import)
    public string Period { get; set; } = WorkPeriod.Other;
    public bool IsUnescoWorldHeritage { get; set; }
    public double? Latitude { get; set; } // WGS 84, set together with Longitude; null = not on the map
    public double? Longitude { get; set; }
    public double? MercatorX { get; private set; } // unit Web Mercator, generated by the database
    public double? MercatorY { get; private set; }
    public bool IsActive { get; set; } = true;
    public int Revision { get; private set; } // bumped by trigger on every update (staff ETag)
    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset UpdatedAt { get; set; }
    public DateTimeOffset? DeletedAt { get; set; } // soft delete; null = not deleted

    public GeoPoint? Location
    {
        get => Latitude is { } latitude && Longitude is { } longitude ? new GeoPoint(latitude, longitude) : null;
        set => (Latitude, Longitude) = (value?.Latitude, value?.Longitude);
    }

    public List<WorkTranslation> Translations { get; set; } = [];
    public List<WorkImage> Images { get; set; } = [];
    public List<WorkPart> Parts { get; set; } = [];
}
